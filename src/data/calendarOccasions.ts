/**
 * Derives the Arabic weekday name strictly from the actual Gregorian date.
 * Guarantees: Gregorian date -> Weekday (completely isolated from lunar/Hijri offset).
 */
export function getArabicWeekdayName(date: Date): string {
  return ARABIC_WEEKDAYS[date.getDay()];
}

// Approximate Gregorian to Hijri algorithm with user adjustment option (-2 to +2 days)
export function getHijriDate(date: Date, adjustmentDays: number = 0): { day: number; month: number; year: number; monthName: string } {
  const d = new Date(date.getTime() + adjustmentDays * 86400000);
  
  // Use Intl if supported
  try {
    const formatter = new Intl.DateTimeFormat('ar-SA-u-ca-islamic-umalqura', {
      day: 'numeric',
      month: 'numeric',
      year: 'numeric',
    });
    const parts = formatter.formatToParts(d);
    let day = 1, month = 1, year = 1448;
    for (const part of parts) {
      if (part.type === 'day') day = parseInt(part.value, 10);
      if (part.type === 'month') month = parseInt(part.value, 10);
      if (part.type === 'year') year = parseInt(part.value, 10);
    }
    if (!isNaN(day) && !isNaN(month) && !isNaN(year)) {
      return {
        day,
        month,
        year,
        monthName: HIJRI_MONTH_NAMES[month - 1] || 'شهر إسلامي',
      };
    }
  } catch (e) {
    // Fallback astronomical calculation
  }

  // Fallback Kuwati/Astronomical algorithm
  const jd = Math.floor(d.getTime() / 86400000) + 2440587.5;
  const l = Math.floor(jd - 1948440 + 10632);
  const n = Math.floor((l - 1) / 10631);
  const l1 = l - 10631 * n + 354;
  const j = (Math.floor((10985 - l1) / 5316)) * (Math.floor((50 * l1) / 17719)) + (Math.floor(l1 / 5670)) * (Math.floor((43 * l1) / 15238));
  const l2 = l1 - (Math.floor((30 - j) / 15)) * (Math.floor((17719 * j) / 50)) - (Math.floor(j / 16)) * (Math.floor((15238 * j) / 43)) + 29;
  const m = Math.floor((24 * l2) / 709);
  const day = l2 - Math.floor((709 * m) / 24);
  const year = 30 * n + j - 30;
  const month = m;

  return {
    day: Math.max(1, Math.min(30, day)),
    month: Math.max(1, Math.min(12, month)),
    year: year > 1400 ? year : 1448,
    monthName: HIJRI_MONTH_NAMES[Math.max(0, Math.min(11, month - 1))],
  };
}
